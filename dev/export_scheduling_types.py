"""Export the three scheduling wire models without starting services or reading secrets.

Run from the repository root using services/scheduling/.venv/Scripts/python.exe.
Only the scalar, enum, reference and nullable shapes used by these models are accepted.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services/scheduling"))

from app.schemas import AppointmentPublic, Money, SlotPublic


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(repr(value) for value in schema["enum"])
    if "const" in schema:
        return repr(schema["const"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "null": "null",
    }[schema["type"]]


lines = ["// Generated by dev/export_scheduling_types.py. Do not edit by hand."]
for model in (Money, SlotPublic, AppointmentPublic):
    schema = model.model_json_schema()
    lines.append(f"export type {model.__name__} = {{")
    for name, value in schema["properties"].items():
        optional = "" if name in schema.get("required", []) else "?"
        lines.append(f"  {name}{optional}: {ts_type(value)}")
    lines.append("}\n")

target = ROOT / "apps/web/src/features/scheduling/types.generated.ts"
target.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {target.relative_to(ROOT)}")
